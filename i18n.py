def t(key):
    """Get a UI string for the current language."""
    block = MESSAGES.get(LANG) or MESSAGES["en"]
    text = block.get(key)
    if text is None:
        text = MESSAGES["en"].get(key, key)
    return text


def toggle():
    """Switch EN <-> RU and return the new language code."""
    global LANG
    LANG = "ru" if LANG == "en" else "en"
    return LANG
